#!/usr/bin/env python3
"""Generate QR test fixtures from independent implementations.

The application carries its own QR encoder, because the device must draw a code with no
network and no camera. A hand-written encoder is exactly the kind of code that looks right
while being wrong, so its output is checked against two other implementations:

  * the `qrcode` package, for the module matrix with the mask forced, which verifies the
    data encoding, the Reed-Solomon codewords, the function patterns, the placement, and
    the format information. The mask is forced because this library scores masks with the
    neighbour-count "lost point" heuristic rather than the penalty the specification
    defines, so its automatic choice can legitimately differ from a spec-faithful encoder.
  * the `segno` package, for which mask the specification's penalty rules select. That is
    the one property the forced-mask comparison cannot cover.

Two libraries, two properties, neither taken on trust.

This script writes tests/qr_expected.inc, which the host test includes. The fixtures are
committed so the tests run without Python and without network; this script exists so the
fixtures can be regenerated and their provenance is not a mystery.

Usage:
    python -m pip install qrcode segno
    python tools/make_qr_fixture.py
"""

from pathlib import Path

import qrcode
import segno
from qrcode.constants import ERROR_CORRECT_L
from qrcode.util import MODE_8BIT_BYTE, QRData

# (name, text, version). The version is the smallest one whose byte-mode capacity at level L
# holds the text, which is also the version the firmware's encoder must choose. Pinning a
# larger version would compare symbols the encoder is right not to produce.
CASES = [
    ("v1_hello", "HELLO", 1),                                                  # 5 bytes
    ("v2_short_wifi", "WIFI:T:WPA;S:Pet;P:12345678;;", 2),                      # 30 bytes
    ("v3_wifi", "WIFI:T:WPA;S:Passport-91E1;P:pae2f91e1;;", 3),                 # 40 bytes
    ("v4_long_wifi",
     "WIFI:T:WPA;S:Passport-91E1-Extended-Name;P:pae2f91e1;H:false;;", 4),      # 62 bytes
]


def add_byte_mode(qr, text):
    """Add the payload in byte mode, with no mode optimisation.

    This matters more than it looks. Both reference libraries pick the most compact
    encoding by default, and "HELLO" or a Wi-Fi string of capitals is more compact in
    alphanumeric mode than in byte mode. A fixture built that way encodes *different
    codewords* from the firmware's byte-mode encoder, and the matrices differ for a reason
    that has nothing to do with correctness. The first version of this script made exactly
    that mistake and sent the search into the placement code for a bug that was not there.
    """
    qr.add_data(QRData(text.encode("utf-8"), mode=MODE_8BIT_BYTE))


def rows_from(matrix):
    return ["".join("1" if cell else "0" for cell in row) for row in matrix]


def emit(path: Path) -> None:
    lines = [
        "// Generated by tools/make_qr_fixture.py. Do not edit by hand.",
        "//",
        "// Matrices: the Python `qrcode` package with the mask forced, one matrix per mask.",
        "// Expected mask: the `segno` package, which follows the specification's penalty",
        "// rules. The host test checks the matrices for every mask and the chosen mask",
        "// separately, so a failure says which of the two is wrong.",
        "",
    ]

    for name, text, version in CASES:
        upper = name.upper()
        for mask in range(8):
            qr = qrcode.QRCode(version=version, error_correction=ERROR_CORRECT_L,
                               box_size=1, border=0)
            add_byte_mode(qr, text)
            qr.makeImpl(False, mask)
            rows = rows_from(qr.modules)
            lines.append(f"// {name}, mask {mask}, version {version}, {len(text)} bytes")
            lines.append(f"static const char *const {upper}_M{mask}[] = {{")
            for row in rows:
                lines.append('    "' + row + '",')
            lines.append("};")
            lines.append("")

        # segno is asked for its mask, but only as recorded information, never as an
        # assertion. Investigated and found not comparable: extracting the codewords from
        # segno's own matrix in the standard order yields
        #     40 54 84 54 C4 C4 F0 00 EC 11 ...      (segno)
        #     40 54 84 54 C4 C4 F0 EC 11 EC 11 ...   (the specification's padding, and
        #                                              what qrcode and the firmware produce)
        # An extra zero byte before the pad codewords means segno encodes a different
        # symbol for the same request, so its mask choice scores a different matrix. Its
        # penalty implementation follows the specification, but it cannot be used as an
        # oracle for this encoder's mask selection until that padding difference is
        # understood. The value is kept here so the comparison is one command away.
        seq = segno.make(text, version=version, error="l", boost_error=False, mode="byte")
        lines.append(f"// {name}: mask chosen by segno (recorded, NOT asserted - see the script)")
        lines.append(f"#define {upper}_SEGNO_MASK {seq.mask}")
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path}: {len(CASES)} cases, 8 forced masks each")


if __name__ == "__main__":
    emit(Path(__file__).resolve().parent.parent / "tests" / "qr_expected.inc")
